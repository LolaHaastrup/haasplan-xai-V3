def sections_for(verdict=None):
    """Return the sections that apply, given the verdict shown."""
    return [(label, items) for label, items, only_if_rejected in QUESTIONNAIRE
            if not (only_if_rejected and verdict == "ACCEPTED")]


def all_items(verdict=None):
    """Flatten to (section, item id, item text).

    verdict="ACCEPTED" omits section F. verdict=None returns every item, which
    is the count to quote when describing the full instrument.
    """
    return [(label, item_id, text)
            for label, items in sections_for(verdict)
            for item_id, text in items]
